const AUTO_HEADER =
  "Generated by scripts/gen-piece-css.mjs — DO NOT EDIT. Re-run the script after changing assets/pieces/.";

function dataUri(file) {
  const ext = EXTENSIONS.find((e) => file.endsWith(e));
  const bin = readFileSync(file);
  return `url("data:${MIME[ext]};base64,${bin.toString("base64")}")`;
}

// Resolve assets/pieces/<set>/<code>.<svg|webp>, or null if absent.
function pieceFile(dir, code) {
  for (const ext of EXTENSIONS) {
    const file = join(dir, `${code}${ext}`);
    if (existsSync(file)) return file;
  }
  return null;
}

// Resolve the per-side shared image assets/pieces/<set>/<w|b>.<svg|webp>.
function sideFile(dir, color) {
  for (const ext of EXTENSIONS) {
    const file = join(dir, `${color}${ext}`);
    if (existsSync(file)) return file;
  }
  return null;
}

// ---- collect valid sets -----------------------------------------------------

if (!existsSync(SRC_DIR)) {
  console.error(`Source directory not found: ${SRC_DIR}`);
  process.exit(1);
}

const sets = [];
for (const entry of readdirSync(SRC_DIR, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const dir = join(SRC_DIR, entry.name);
  const missing = PIECE_FILES.filter((code) => pieceFile(dir, code) === null);
  if (missing.length > 0) {
    // Shared-art set: no per-piece files, but both side images present —
    // all pieces of a side share one image (e.g. lila's "disguised").
    if (
      missing.length !== PIECE_FILES.length ||
      !sideFile(dir, "w") ||
      !sideFile(dir, "b")
    ) {
      console.warn(`SKIP ${entry.name}/ — missing: ${missing.join(", ")}`);
      continue;
    }
  }
  sets.push(entry.name);
}

sets.sort((a, b) => {
  const ia = CANONICAL_ORDER.indexOf(a);
  const ib = CANONICAL_ORDER.indexOf(b);
  if (ia === -1 && ib === -1) return a.localeCompare(b);
  if (ia === -1) return 1;
  if (ib === -1) return -1;
  return ia - ib;
});

if (sets.length === 0) {
  console.error("No valid piece sets found.");
  process.exit(1);
}

// ---- build outputs ----------------------------------------------------------

const outputs = new Map(); // path -> content

for (const set of sets) {
  const dir = join(SRC_DIR, set);
  let css = `/* ${AUTO_HEADER} Source: assets/pieces/${set}/ */\n`;
  const sharedW = sideFile(dir, "w");
  const sharedB = sideFile(dir, "b");
  if (sharedW && sharedB && pieceFile(dir, "wK") === null) {
    // Shared-art set: a single rule per side covers every piece kind and
    // the picker thumbnail. Thumbnail selectors must require the scope
    // class ON the picker tile itself — see the comment below.
    for (const [c, file] of [
      ["w", sharedW],
      ["b", sharedB],
    ]) {
      const selectors = Object.values(KIND).map(
        (kind) => `.ct-pieceset-${set} .cg-wrap piece.${kind}.${COLOR[c]}`,
      );
      selectors.push(
        `.ct-piece-set-picker__tile.ct-pieceset-${set} .ct-piece-thumb.${c}N`,
      );
      css += `${selectors.join(",\n")} {\n  background-image: ${dataUri(file)};\n}\n`;
    }
    outputs.set(join(CSS_DIR, `${set}.css`), css);
    continue;
  }
  for (const code of PIECE_FILES) {
    const color = COLOR[code[0]];
    const kind = KIND[code[1]];
    css += `.ct-pieceset-${set} .cg-wrap piece.${kind}.${color} {\n  background-image: ${dataUri(pieceFile(dir, code))};\n}\n`;
  }
  // Thumbnail rules must require the scope class ON the picker tile itself
  // (`.ct-piece-set-picker__tile.ct-pieceset-<set>`): applyPieceSet() keeps a
  // `.ct-pieceset-<current>` class on <body>, and a plain descendant selector
  // would let the body-level rule leak into every tile of the picker and
  // (being later in the cascade for late-ordered sets) override their own
  // artwork.
  for (const code of THUMB_FILES) {
    css += `.ct-piece-set-picker__tile.ct-pieceset-${set} .ct-piece-thumb.${code} {\n  background-image: ${dataUri(pieceFile(dir, code))};\n}\n`;
  }
  outputs.set(join(CSS_DIR, `${set}.css`), css);
}

outputs.set(
  INDEX_CSS,
  `/* ${AUTO_HEADER} */\n${sets.map((set) => `@import "./${set}.css";\n`).join("")}`,
);

const registry = sets.map((set) => {
  const name =
    DISPLAY_NAMES[set] ??
    set.replace(/(^|[-_])(\w)/g, (_, __, c) => ` ${c.toUpperCase()}`).trim();
  return `  { key: "${set}", name: "${name}" },`;
});
outputs.set(
  GEN_TS,
  `// ${AUTO_HEADER}\n\nexport interface PieceSetDef {\n  key: string;\n  name: string;\n}\n\nexport const PIECE_SETS: readonly PieceSetDef[] = [\n${registry.join("\n")}\n];\n`,
);

// ---- write or check ---------------------------------------------------------

mkdirSync(CSS_DIR, { recursive: true });

let failures = 0;

// Orphaned per-set CSS files (their source directory was removed/renamed).
for (const file of readdirSync(CSS_DIR)) {
  if (!file.endsWith(".css")) continue;
  if (outputs.has(join(CSS_DIR, file))) continue;
  if (CHECK) {
    console.error(`ORPHAN: ${join(CSS_DIR, file)}`);
    failures++;
  } else {
    rmSync(join(CSS_DIR, file));
    console.log(`DELETE: ${join(CSS_DIR, file)}`);
  }
}
for (const [path, content] of outputs) {
  const existing = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (existing === content) continue;
  if (CHECK) {
    console.error(`STALE: ${path}`);
    failures++;
  } else {
    writeFileSync(path, content);
    console.log(`WRITE: ${path}`);
  }
}

if (CHECK) {
  if (failures > 0) {
    console.error(
      `${failures} generated file(s) out of date — re-run: node scripts/gen-piece-css.mjs`,
    );
    process.exit(1);
  }
  console.log(
    `OK — ${sets.length} piece sets, all generated files up to date.`,
  );
} else {
  console.log(`Done — ${sets.length} piece sets generated.`);
}
