// Generates piece-set CSS + registry from assets/pieces/ (single source of
// truth: one sub-directory per piece set, holding the 12 standard SVGs
// wK wQ wR wB wN wP bK bQ bR bB bN bP — or just w.svg + b.svg for sets
// where all pieces of a side share one image, e.g. lila's "disguised").
//
//   node scripts/gen-piece-css.mjs          generate (write files)
//   node scripts/gen-piece-css.mjs --check  verify outputs are up to date
//
// Outputs (all committed to the repo, bundled into styles.css by Vite):
//   src/style/pieceSets/<set>.css  12 board rules + 2 thumbnail rules,
//                                  base64 data URIs scoped under
//                                  .ct-pieceset-<set>
//   src/style/pieceSets/index.css  @import list, lichess canonical order
//   src/pieceSets.gen.ts           PIECE_SETS registry for settings UI
//
// Directories missing any of the 12 standard files are skipped with a
// warning (e.g. lila's "mono" fallback set) — add or remove a set by
// adding or removing its directory, then re-run this script.

import {
  readFileSync,
  writeFileSync,
  existsSync,
  readdirSync,
  mkdirSync,
  rmSync,
} from "node:fs";
import { join } from "node:path";

const ROOT = import.meta.dirname;
const SRC_DIR = join(ROOT, "..", "assets", "pieces");
const CSS_DIR = join(ROOT, "..", "src", "style", "pieceSets");
const INDEX_CSS = join(CSS_DIR, "index.css");
const GEN_TS = join(ROOT, "..", "src", "pieceSets.gen.ts");

const CHECK = process.argv.includes("--check");

// The 12 standard piece images every set must provide (SVG preferred;
// WebP accepted — lila's "monarchy" ships only WebP).
const PIECE_FILES = [
  "wK",
  "wQ",
  "wR",
  "wB",
  "wN",
  "wP",
  "bK",
  "bQ",
  "bR",
  "bB",
  "bN",
  "bP",
];

const MIME = { ".svg": "image/svg+xml", ".webp": "image/webp" };
const EXTENSIONS = Object.keys(MIME);

// File code -> chessground element classes (e.g. wK -> piece.king.white).
const KIND = {
  K: "king",
  Q: "queen",
  R: "rook",
  B: "bishop",
  N: "knight",
  P: "pawn",
};
const COLOR = { w: "white", b: "black" };

// Thumbnail preview files (shown in the board-menu picker).
const THUMB_FILES = ["wN", "bN"];

// Canonical display order (matches lila pref.PieceSet). Unknown
// directories are appended after these, alphabetically.
